/***********************************************
 * LED 驱动 (系统运行状态指示)
 ***********************************************/
#include "led.h"

/**************************************************************************
函数功能：LED 闪烁
入口参数：time=闪烁频率 (0=关闭)
返回  值：无
**************************************************************************/
void Led_Flash(u16 time)
{
    static int temp;
    if(0 == time) LED = 0;
    else if(++temp == time) LED = ~LED, temp = 0;
}
